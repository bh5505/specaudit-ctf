#!/usr/bin/env python3
"""Build the scoped live-fire target list for the Glasswing pre-test loop.

Inputs
  - report.json from the baseline run  -> T1 findings (address-scoped)
  - pack_evidence.duckdb               -> reproduction-queue candidates (lanes),
                                          owned IPv4 ranges, exposed services

Selection (task step 2):
  1. take the reproduction queue (lane per candidate),
  2. keep only addresses that a T1 check also flagged,
  3. restrict to lab / RFC1918 / CGNAT / loopback / org-owned-range space,
  4. rank by T1 severity then lane priority, cap at --max-targets.

Anything public and outside an org-owned range is NOT probed: it stays queued
and is written to queued_public.csv with the reason.

Outputs (in --out-dir):
  targets.txt          one "ip proto/port" line per selectable target (comment header)
  targets.csv          full selection detail (all T1+queue IPs, with disposition)
  queued_public.csv    the public remainder, with the block reason

No traffic is generated by this script.
"""
import argparse
import csv
import ipaddress
import json
import os
from collections import defaultdict

import duckdb

RUN = "gw-asmvm-20260902"
T1_PREFIX = "ext_telecom_asmvm_t1_"

# lane -> probe priority (lower = probe first) and the port intent
LANE_PRIORITY = {
    "live_fire_probe_tls": 0,
    "banner_reverify_probe": 1,
    "live_fire_probe_generic": 2,
    "live_fire_probe_udp_tcp": 3,
    "credentialed_scan": 4,
}
# credentialed_scan needs scanner credentials we do not have; it is never a
# banner-grab target.
NON_PROBEABLE_LANES = {"credentialed_scan"}

SEV_RANK = {"Critical": 0, "Critical/High": 0, "High": 1, "Medium": 2,
            "Low": 3, "Informational": 4, "": 5}


def ip_to_int(text):
    try:
        return int(ipaddress.IPv4Address(text.strip()))
    except Exception:
        return None


CGNAT = ipaddress.ip_network("100.64.0.0/10")


def classify(ip):
    """lab / RFC1918 / CGNAT / link-local / loopback are ours to probe."""
    try:
        addr = ipaddress.ip_address(ip.strip())
    except Exception:
        return "not_ipv4"
    if addr.version == 4 and addr in CGNAT:
        return "cgnat"
    if addr.is_loopback:
        return "loopback"
    if addr.is_private or addr.is_link_local:
        return "lab_rfc1918"
    return "public"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", required=True,
                    help="runner report.json to pull T1 addresses from")
    ap.add_argument("--db", required=True,
                    help="evidence DuckDB with the address spine / owned ranges")
    ap.add_argument("--out-dir", default="livefire_out")
    ap.add_argument("--max-targets", type=int, default=20)
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    # ---- 1. T1 findings -> addresses -------------------------------------
    doc = json.load(open(args.report, encoding="utf-8"))
    t1 = defaultdict(lambda: {"checks": set(), "max_sev": 0.0, "details": ""})
    for f in doc["findings"]:
        cid = f["check_id"]
        if not cid.startswith(T1_PREFIX):
            continue
        loc = f.get("record_locator", "") + " " + f.get("details", "")
        for tok in loc.replace(";", " ").replace(",", " ").split():
            for part in tok.replace("+", " ").split(":"):
                n = ip_to_int(part)
                if n is None:
                    continue
                ent = t1[part]
                ent["checks"].add(cid.replace(T1_PREFIX, ""))
                try:
                    ent["max_sev"] = max(
                        ent["max_sev"], float(f.get("risk_score", 0)))
                except (TypeError, ValueError):
                    pass
                if not ent["details"]:
                    ent["details"] = f.get("details", "")[:300]
    print("T1 findings: %d address-scoped rows over %d distinct IPv4"
          % (sum(1 for f in doc["findings"] if f["check_id"].startswith(T1_PREFIX)), len(t1)))

    # ---- 2. reproduction queue (lanes) ----------------------------------
    con = duckdb.connect(args.db, read_only=True)
    lane_sql = """
        SELECT subject_ip,
               CASE WHEN candidate_source_system = 'ivanti_neurons'
                         THEN 'credentialed_scan'
                    WHEN candidate_source_system = 'cortex_xpanse'
                         AND subject_kind = 'cve'
                         THEN 'banner_reverify_probe'
                    WHEN rule_name IN ('SnmpServer','IkeV1Server','NtpServer','SipServer',
                                       'NetBiosServer','MssqlServer','RdpServer','SshServer',
                                       'TelnetServer')
                         THEN 'live_fire_probe_udp_tcp'
                    WHEN rule_name LIKE '%Certificate%' OR rule_name LIKE 'InsecureTLS%'
                         OR rule_name LIKE '%CbcCipher%'
                         THEN 'live_fire_probe_tls'
                    ELSE 'live_fire_probe_generic' END AS lane,
               COUNT(*) AS candidates,
               MAX(COALESCE(rule_name, '')) AS sample_rule,
               MAX(COALESCE(severity, '')) AS vendor_severity
        FROM ext_telecom_asmvm_candidate_subject
        WHERE run_id = ? AND subject_ip IS NOT NULL AND subject_ip <> ''
        GROUP BY 1, 2
    """
    queue = defaultdict(list)
    for ip, lane, cands, rule, sev in con.execute(lane_sql, [RUN]).fetchall():
        queue[ip.strip()].append({"lane": lane, "candidates": cands,
                                  "sample_rule": rule, "vendor_severity": sev})
    print("queue: %d candidates over %d distinct subject IPv4"
          % (sum(len(v) for v in queue.values()), len(queue)))

    # ---- 3. owned ranges + exposed service ports -------------------------
    owned = con.execute(
        "SELECT ip_from, ip_to FROM ext_telecom_asmvm_owned_ip_range "
        "WHERE run_id = ? AND ip_version = 4 AND ip_from IS NOT NULL", [RUN]).fetchall()
    # merge first so the point lookup cannot be fooled by nested/overlapping ranges
    merged = []
    for a, b in sorted(owned):
        if merged and a <= merged[-1][1] + 1:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    print("owned IPv4 ranges: %d (merged to %d disjoint)" % (len(owned), len(merged)))

    def in_owned(ip):
        n = ip_to_int(ip)
        if n is None:
            return False
        lo, hi = 0, len(merged) - 1
        while lo <= hi:
            mid = (lo + hi) // 2
            a, b = merged[mid]
            if n < a:
                hi = mid - 1
            elif n > b:
                lo = mid + 1
            else:
                return True
        return False

    ports = defaultdict(list)
    for ipv4_list, port, proto, active, name in con.execute(
            "SELECT ipv4_list, port, protocol, is_active, service_name "
            "FROM ext_telecom_asmvm_service WHERE run_id = ?", [RUN]).fetchall():
        if not ipv4_list:
            continue
        for one in str(ipv4_list).split(","):
            one = one.strip()
            if ip_to_int(one) is not None:
                ports[one].append((str(proto or "tcp"), str(port or ""),
                                   str(active), (name or "")[:40]))

    # ---- 4. classify + rank ---------------------------------------------
    rows, probeable = [], []
    for ip in sorted(set(t1) | set(queue), key=lambda x: ip_to_int(x) or 0):
        klass = classify(ip)
        owned_flag = in_owned(ip)
        lanes = sorted({q["lane"] for q in queue.get(ip, [])})
        rec = {
            "ip": ip,
            "address_class": klass,
            "in_owned_range": owned_flag,
            "t1_checks": "|".join(sorted(t1[ip]["checks"])) if ip in t1 else "",
            "t1_max_risk": t1[ip]["max_sev"] if ip in t1 else "",
            "queue_lanes": "|".join(lanes),
            "queue_candidates": sum(q["candidates"] for q in queue.get(ip, [])),
            "sample_rule": max((q["sample_rule"] for q in queue.get(ip, [])),
                               key=len) if ip in queue else "",
            "probed": "",
            "disposition": "",
            "services_seen_in_export": ";".join(
                "%s/%s%s" % (p, pt, "" if a in ("true", "True", "1") else " (inactive)")
                for p, pt, a, _ in sorted(set(ports.get(ip, [])))[:8]),
        }
        is_lab = klass in ("lab_rfc1918", "cgnat", "loopback")
        if not (ip in t1 and ip in queue):
            rec["disposition"] = "not_in_both_t1_and_queue"
        elif is_lab:
            rec["disposition"] = "probe_lab"
        elif owned_flag:
            rec["disposition"] = ("queued_org_owned_public_range "
                                 "(egress-guard: not a lab host, needs user approval)")
        else:
            rec["disposition"] = "queued_public (egress-guard: not ours to touch)"
        if rec["disposition"] == "probe_lab":
            probeable.append(rec)
        rows.append(rec)

    probeable.sort(key=lambda r: (-float(r["t1_max_risk"] or 0),
                                  min((LANE_PRIORITY.get(l, 9)
                                       for l in r["queue_lanes"].split("|")
                                       if l not in NON_PROBEABLE_LANES),
                                      default=9),
                                  ip_to_int(r["ip"])))

    # ---- 5. write -------------------------------------------------------
    fieldnames = list(rows[0].keys()) if rows else ["ip"]
    with open(os.path.join(args.out_dir, "targets.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)

    with open(os.path.join(args.out_dir, "queued_public.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames)
        w.writeheader()
        w.writerows([r for r in rows if r["disposition"].startswith("queued_")])

    chosen = probeable[:args.max_targets]
    with open(os.path.join(args.out_dir, "targets.txt"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("# Glasswing live-fire scoped target list\n")
        fh.write("# run: gw-livefire (engagement glasswing-2026)  base run: %s\n" % RUN)
        fh.write("# selection: reproduction-queue candidates AND a T1 finding, "
                 "restricted to lab/RFC1918/CGNAT/loopback or an org-owned range\n")
        fh.write("# population: %d address-bearing T1/queue IPv4; lab-scoped %d; "
                 "org-owned-public %d; public-queued %d\n" % (
                     len(rows),
                     len(probeable),
                     sum(1 for r in rows
                         if r["disposition"].startswith("queued_org_owned")),
                     sum(1 for r in rows
                         if r["disposition"].startswith("queued_public "))))
        fh.write("# cap: %d.  Nothing outside lab space is probed; see queued_public.csv\n"
                 % args.max_targets)
        for rec in chosen:
            fh.write("%s\n" % rec["ip"])
        if not chosen:
            fh.write("# NO LAB-SPACE TARGET EXISTS IN THE EVIDENCE: every queued candidate "
                     "address is public. See queued_public.csv; those hosts stay queued.\n")
    for rec in chosen:
        rec["probed"] = "selected"

    print("\ndisposition summary:")
    tally = defaultdict(int)
    for r in rows:
        tally[r["disposition"]] += 1
    for k, v in sorted(tally.items(), key=lambda kv: -kv[1]):
        print("  %-70s %d" % (k, v))
    print("\nlab-space targets selected: %d (cap %d)" % (len(chosen), args.max_targets))
    for rec in chosen[:20]:
        print("   %-16s t1=%s lanes=%s" % (rec["ip"], rec["t1_checks"], rec["queue_lanes"]))
    print("\nwrote targets.txt / targets.csv / queued_public.csv in %s" % args.out_dir)


if __name__ == "__main__":
    main()
