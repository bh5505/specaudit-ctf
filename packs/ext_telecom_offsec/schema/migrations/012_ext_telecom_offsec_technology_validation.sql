-- Technology findings and the expected membership are imported from one
-- complete, scoped validator inventory. The receipt survives an empty export.
-- Validation observations are independently produced by the validator.
-- A missing observation remains visible; it is never a clean verdict.

CREATE TABLE IF NOT EXISTS ext_telecom_offsec_technology_candidate (
    run_id                    VARCHAR NOT NULL,
    engagement_id             VARCHAR NOT NULL,
    validator_project_id      VARCHAR NOT NULL,
    validator_engagement_id   VARCHAR NOT NULL,
    accept_event_id           VARCHAR NOT NULL DEFAULT '00000000-0000-0000-0000-000000000000',
    finding_id                VARCHAR NOT NULL,
    source_run_id             VARCHAR,
    inventory_snapshot_id     VARCHAR NOT NULL,
    rule_id                   VARCHAR NOT NULL,
    provider                  VARCHAR NOT NULL,
    resource_uid              VARCHAR,
    account_id                VARCHAR,
    region                    VARCHAR,
    severity                  VARCHAR,
    title                     VARCHAR,
    source_system             VARCHAR,
    source_file               VARCHAR,
    source_row_id             VARCHAR,
    record_hash               VARCHAR,
    lineage_batch_id          VARCHAR,
    mapping_version           VARCHAR,
    model_version             VARCHAR,
    PRIMARY KEY (run_id, accept_event_id, engagement_id,
                 validator_project_id, validator_engagement_id, finding_id)
);

