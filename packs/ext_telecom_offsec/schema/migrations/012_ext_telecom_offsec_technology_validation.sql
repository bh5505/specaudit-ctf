    rule_id                   VARCHAR NOT NULL,
    provider                  VARCHAR NOT NULL,
    resource_uid              VARCHAR NOT NULL,
    account_id                VARCHAR,
    region                    VARCHAR,
    configuration_status      VARCHAR NOT NULL,
    reachability_status       VARCHAR NOT NULL,
    verdict                   VARCHAR NOT NULL,
    finished_at               TIMESTAMP,
    receipt_sha256            VARCHAR NOT NULL,
    source_system             VARCHAR,
    source_file               VARCHAR,
    source_row_id             VARCHAR,
    record_hash               VARCHAR,
    lineage_batch_id          VARCHAR,
