    model_version             VARCHAR,
    PRIMARY KEY (run_id, accept_event_id, engagement_id,
                 validator_project_id, validator_engagement_id, attempt_id)
);

CREATE TABLE IF NOT EXISTS ext_telecom_offsec_technology_inventory_receipt (
